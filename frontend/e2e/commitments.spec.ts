import { expect, test } from '@playwright/test';
import { isolateHousehold } from './household';

test('bike without card, partial installments and Netflix confirmation', async ({ page }, testInfo) => {
  await isolateHousehold(page, 'Compromisos E2E');
  await page.goto('/app/accounts');
  await page.getByRole('button', { name: 'Agregar cuenta' }).click();
  await page.getByLabel('Nombre', { exact: true }).fill('Banco compromisos');
  await page.getByLabel('Saldo inicial').fill('100');
  await page.getByLabel('Fecha de apertura').fill('2026-09-01');
  await page.getByRole('button', { name: 'Guardar cuenta' }).click();
  await expect(page.getByText('Cuenta guardada.')).toBeVisible();
  await page.goto('/app/installments');
  await page.getByRole('button', { name: 'Nueva compra en cuotas' }).click();
  await page.getByLabel('Descripción').fill('Bicicleta');
  await page.getByLabel('Vendedor o acreedor').fill('Bicicletería');
  await page.getByLabel('Importe total').fill('90,01');
  await page.getByLabel('Fecha de la primera cuota').fill('2026-10-31');
  await page.getByLabel('Cantidad de cuotas').fill('3');
  await page.getByRole('combobox', { name: 'Categoría', exact: true }).selectOption({ label: 'Transporte' });
  await page.getByRole('button', { name: 'Guardar compra' }).click();
  await expect(page.getByRole('button', { name: 'Pagar cuota', exact: true })).toHaveCount(3);
  let summary = await (await page.request.get('/api/v1/dashboard/summary/?month=2026-10')).json();
  expect(summary.available_balances[0].amount).toBe('100.00');
  expect(summary.expense).toBe('30.01');
  await page.getByRole('button', { name: 'Pagar cuota', exact: true }).first().click();
  await page.getByRole('combobox', { name: 'Cuenta de origen', exact: true }).selectOption({ index: 1 });
  await page.getByLabel('Importe a pagar').fill('10');
  await page.getByLabel('Fecha de pago').fill('2026-10-12');
  await page.getByRole('button', { name: 'Registrar pago' }).click();
  await expect(page.getByText('Pago parcial · Pendiente $ 20,01')).toBeVisible();
  await expect(page.getByText('Pago efectuado: $ 10,00', { exact: false })).toBeVisible();
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  await page.screenshot({ path: testInfo.outputPath('installments.png'), fullPage: true });
  await page.goto('/app/recurring');
  await page.getByRole('button', { name: 'Nueva recurrencia' }).click();
  await page.getByLabel('Nombre', { exact: true }).fill('Netflix');
  await page.getByLabel('Importe', { exact: true }).fill('10');
  await page.getByRole('combobox', { name: 'Categoría', exact: true }).selectOption({ label: 'Suscripciones' });
  await page.getByLabel('Fecha de inicio').fill('2026-10-01');
  await page.getByLabel('Día de vencimiento').fill('15');
  await page.getByRole('combobox', { name: 'Cuenta de pago opcional' }).selectOption({ label: 'Banco compromisos' });
  await page.getByRole('button', { name: 'Guardar recurrencia' }).click();
  await expect(page.getByRole('button', { name: 'Pagar ocurrencia' })).toHaveCount(3);
  await page.getByRole('button', { name: 'Modificar importe' }).first().click();
  await page.getByLabel('Importe de esta ocurrencia').fill('12,50');
  await page.getByRole('button', { name: 'Guardar importe' }).click();
  await page.getByRole('button', { name: 'Pagar ocurrencia' }).first().click();
  await page.getByLabel('Fecha de pago').fill('2026-10-15');
  await page.getByRole('button', { name: 'Confirmar pago', exact: true }).click();
  await expect(page.getByText('Gasto realizado · Pago efectuado 2026-10-15 desde Banco compromisos')).toBeVisible();
  await expect(page.getByRole('button', { name: 'Pagar ocurrencia' })).toHaveCount(2);
  await page.getByRole('button', { name: 'Pausar', exact: true }).click();
  await expect(page.getByText('Pausada', { exact: true })).toBeVisible();
  await expect(page.getByRole('button', { name: 'Pagar ocurrencia' })).toHaveCount(0);
  await page.getByRole('button', { name: 'Reanudar', exact: true }).click();
  await expect(page.getByRole('button', { name: 'Pagar ocurrencia' })).toHaveCount(2);
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  await page.screenshot({ path: testInfo.outputPath('recurring.png'), fullPage: true });
  await page.goto('/app');
  await page.getByLabel('Mes', { exact: true }).fill('2026-10');
  await expect(page.getByTestId('available-balance')).toContainText('77,50');
  await expect(page.getByTestId('monthly-expense')).toContainText('42,51');
  await expect(page.getByText('Bicicleta', { exact: false }).first()).toBeVisible();
  await expect(page.getByText('Netflix · Vence 2026-11-15')).toBeVisible();
  summary = await (await page.request.get('/api/v1/dashboard/summary/?month=2026-10')).json();
  expect(summary.card_pending).toBe('80.01');
});
