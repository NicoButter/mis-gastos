import { expect, test } from '@playwright/test';

test('six installments and account payment without duplicate expense', async ({ page }, testInfo) => {
  await page.goto('/app/accounts');
  await page.getByRole('button', { name: 'Agregar cuenta' }).click();
  await page.getByLabel('Nombre', { exact: true }).fill('Banco tarjetas');
  await page.getByLabel('Saldo inicial').fill('200');
  await page.getByRole('button', { name: 'Guardar cuenta' }).click();
  await expect(page.getByText('Cuenta guardada.')).toBeVisible();
  await page.goto('/app/cards');
  await page.getByRole('button', { name: 'Agregar tarjeta' }).click();
  await page.getByLabel('Banco', { exact: true }).fill('Banco');
  await page.getByLabel('Nombre', { exact: true }).fill('Visa');
  await page.getByRole('button', { name: 'Guardar tarjeta' }).click();
  await expect(page.getByRole('button', { name: 'Registrar compra' })).toBeVisible();
  await page.getByRole('button', { name: 'Registrar compra' }).click();
  await page.getByLabel('Descripción').fill('Heladera seis cuotas');
  await page.getByLabel('Importe total').fill('100');
  await page.getByLabel('Fecha de compra').fill('2026-01-20');
  await page.getByLabel('Cantidad de cuotas').fill('6');
  await page.getByLabel('Categoría').selectOption({ label: 'Alimentación' });
  await page.getByRole('button', { name: 'Guardar compra' }).click();
  await expect(page.getByRole('button', { name: 'Pagar cuota', exact: true })).toHaveCount(6);
  await expect(page.getByText('Total $ 100,00 · Pendiente $ 100,00', { exact: false })).toBeVisible();
  await page.getByRole('button', { name: 'Pagar cuota', exact: true }).first().click();
  await page.getByLabel('Cuenta de origen').selectOption({ index: 1 });
  await page.getByLabel('Fecha de pago').fill('2026-02-10');
  await page.getByRole('button', { name: 'Registrar pago' }).click();
  await expect(page.getByRole('button', { name: 'Pagar cuota', exact: true })).toHaveCount(5);
  await expect(page.getByText('Pagada 2026-02-10 desde Banco tarjetas')).toBeVisible();
  await expect(page.getByText('Total $ 100,00 · Pendiente $ 83,33', { exact: false })).toBeVisible();
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true);
  await page.screenshot({ path: testInfo.outputPath('cards.png'), fullPage: true });
  await page.goto('/app');
  await page.getByLabel('Mes', { exact: true }).fill('2026-02');
  await expect(page.getByText('Pendiente total: $ 83,33')).toBeVisible();
  await expect(page.getByText('Vence 2026-03-10')).toBeVisible();
  await expect(page.locator('article').filter({ hasText: 'Gastos del mes' })).toContainText('$ 16,67');
});
